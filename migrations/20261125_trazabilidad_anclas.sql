-- Apply through the controlled migration workflow; never at application startup.
BEGIN;

CREATE TABLE IF NOT EXISTS public.anclas_trazabilidad (
    id_ancla BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tipo_recurso VARCHAR(40) NOT NULL CHECK (tipo_recurso IN ('resena', 'decision_ia')),
    id_recurso BIGINT NOT NULL,
    hash_canonico CHAR(64) NOT NULL CHECK (hash_canonico ~ '^[0-9a-f]{64}$'),
    hash_previo CHAR(64) NULL CHECK (hash_previo IS NULL OR hash_previo ~ '^[0-9a-f]{64}$'),
    estado VARCHAR(20) NOT NULL DEFAULT 'pendiente'
        CHECK (estado IN ('pendiente', 'simulado', 'enviado', 'fallido')),
    hash_transaccion VARCHAR(160),
    intentos INTEGER NOT NULL DEFAULT 0 CHECK (intentos >= 0),
    ultimo_error VARCHAR(500),
    creado_en TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    actualizado_en TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (tipo_recurso, id_recurso, hash_canonico)
);

CREATE INDEX IF NOT EXISTS anclas_trazabilidad_pendientes
    ON public.anclas_trazabilidad (estado, creado_en)
    WHERE estado IN ('pendiente', 'fallido');

COMMIT;
